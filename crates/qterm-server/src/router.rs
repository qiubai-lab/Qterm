use crate::{auth, catalog, files, socket, state::ServerState, transfers, vault};
use axum::{
    Json, Router,
    extract::DefaultBodyLimit,
    http::{HeaderValue, header},
    middleware,
    routing::{get, post},
};
use std::sync::Arc;
use tower_http::{services::ServeDir, set_header::SetResponseHeaderLayer};

pub fn router(state: Arc<ServerState>) -> Router {
    let protected=Router::new()
        .route("/auth",get(||async{Json(serde_json::json!({"authenticated":true,"runtime":"web-server","protocolVersion":1,"version":env!("CARGO_PKG_VERSION")}))}))
        .route("/logout",post(auth::logout))
        .route("/profiles",get(catalog::profiles).post(catalog::create_profile))
        .route("/profiles/{id}",axum::routing::put(catalog::update_profile).delete(catalog::delete_profile))
        .route("/profiles/{id}/requirements",get(catalog::requirements))
        .route("/profiles/candidates",post(catalog::candidates))
        .route("/groups",get(catalog::groups).post(catalog::create_group))
        .route("/groups/{id}",axum::routing::put(catalog::update_group).delete(catalog::delete_group))
        .route("/workspace",get(catalog::load_workspace).put(catalog::save_workspace))
        .route("/runtime/panes/{key}",get(crate::workspace_runtime::pane).put(crate::workspace_runtime::save_pane))
        .route("/runtime/sessions",get(crate::retained_socket::list))
        .route("/runtime/sessions/{id}",axum::routing::delete(crate::retained_socket::destroy))
        .route("/runtime/attach",get(crate::retained_socket::upgrade))
        .route("/sessions",get(socket::upgrade))
        .route("/local/sessions",get(crate::local_socket::upgrade))
        .route("/local/capabilities",get(crate::local_socket::capabilities))
        .route("/local/files/roots",get(crate::local_files::roots))
        .route("/local/files/list",post(crate::local_files::list))
        .route("/local/files/read",post(crate::local_files::read))
        .route("/local/files/binary",post(crate::local_files::binary))
        .route("/local/files/write",post(crate::local_files::write))
        .route("/local/files/create",post(crate::local_files::create))
        .route("/local/files/copy",post(crate::local_files::copy))
        .route("/local/files/rename",post(crate::local_files::rename))
        .route("/local/files/delete",post(crate::local_files::delete))
        .route("/settings",get(crate::settings::get))
        .route("/settings/security",axum::routing::put(crate::settings::security))
        .route("/settings/appearance",axum::routing::put(crate::settings::appearance))
        .route("/settings/terminal",axum::routing::put(crate::settings::terminal))
        .route("/vault",get(vault::status))
        .route("/vault/recovery",post(vault::prepare_recovery))
        .route("/vault/recovery/{id}",get(vault::download_recovery))
        .route("/vault/initialize",post(vault::initialize))
        .route("/vault/unlock",post(vault::unlock))
        .route("/vault/lock",post(vault::lock))
        .route("/credentials",get(vault::list).post(vault::create_password))
        .route("/credentials/drafts/generate",post(crate::credential_management::generate))
        .route("/credentials/drafts/import",post(crate::credential_management::import))
        .route("/credentials/drafts/{id}",post(crate::credential_management::commit).delete(crate::credential_management::cancel))
        .route("/credentials/{id}/password",post(crate::credential_management::reveal))
        .route("/vault/password",axum::routing::put(crate::credential_management::change))
        .route("/vault/clear",post(crate::credential_management::clear))
        .route("/vault/reset/prepare",post(vault::prepare_reset))
        .route("/vault/reset",post(vault::reset).delete(vault::cancel_reset))
        .route("/credentials/generate",post(vault::generate))
        .route("/credentials/{id}",axum::routing::put(vault::rename).delete(vault::delete))
        .route("/credentials/{id}/public-key",get(vault::public_key))
        .route("/files/list",post(files::list)).route("/files/read",post(files::read))
        .route("/files/binary",post(files::binary)).route("/files/write",post(files::write))
        .route("/files/create",post(files::create)).route("/files/copy",post(files::copy))
        .route("/files/rename",post(files::rename)).route("/files/delete",post(files::delete))
        .route("/transfers/upload",post(transfers::upload).layer(DefaultBodyLimit::max(transfers::MAX_TRANSFER_BYTES as usize+1024*1024)))
        .route("/transfers/download",post(transfers::prepare_download))
        .route("/transfers/{id}/cancel",post(crate::transfer_lifecycle::cancel))
        .route("/downloads/{id}",get(transfers::download))
        .route_layer(middleware::from_fn_with_state(state.clone(),auth::guard));
    Router::new()
        .route("/healthz",get(||async{"ok"}))
        .nest("/api/v1",protected.route("/login",post(auth::login)))
        .fallback_service(ServeDir::new(&state.config.assets).append_index_html_on_directories(true))
        .layer(DefaultBodyLimit::max(4*1024*1024))
        .layer(SetResponseHeaderLayer::overriding(header::CACHE_CONTROL,HeaderValue::from_static("no-store")))
        .layer(SetResponseHeaderLayer::overriding(header::X_CONTENT_TYPE_OPTIONS,HeaderValue::from_static("nosniff")))
        .layer(SetResponseHeaderLayer::overriding(header::CONTENT_SECURITY_POLICY,HeaderValue::from_static("default-src 'self'; script-src 'self'; style-src 'self' 'unsafe-inline'; img-src 'self' data: blob:; connect-src 'self'; font-src 'self' data:; object-src 'none'; base-uri 'self'; frame-ancestors 'none'; form-action 'self'")))
        .with_state(state)
}
