"""Connection retirement exercises the production environment/close/pool implementation."""
def run(app, gateways, add):
    app.open('persist-a', 'A', gateways['A'])
    app.open('persist-b', 'B', gateways['B'])
    app.evaluate('persist-a', "await fetch('/set?cookie='+encodeURIComponent('persist=A; Path=/; Max-Age=3600; HttpOnly'));return true")
    app.send(op='fail-close-once');app.wait('failure-armed')
    app.send(op='disconnect',profile='A')
    failed=app.wait('error')
    add('close barrier failure reports error and quarantines generation','injected close barrier timeout' in failed['error'],failed)
    app.send(op='open',id='unsafe-reopen',profile='A',port=gateways['A'].server_address[1],path='/')
    rejected=app.wait('error')
    add('failed retirement cannot reuse or replace context prematurely','正在关闭' in rejected['error'],rejected)
    app.send(op='disconnect', profile='A')
    retired = app.wait('disconnected', profile='A')
    add('disconnect A retires its environment while B remains', retired['environments'] == 1, retired)
    app.send(op='eval', id='persist-a', tag='closed', script='return true')
    add('disconnect closes every A guest', 'unknown window' in app.wait('error')['error'])
    b = app.evaluate('persist-b', "return await fetch('/echo').then(r=>r.json())")
    add('B requests remain isolated after A retirement', b['profile']=='B' and 'session=B' in b['cookie'], b)
    app.send(op='disconnect', profile='A')
    add('repeat disconnect is idempotent', app.wait('disconnected',profile='A')['environments']==1)
    app.open('reborn-a', 'A', gateways['A'])
    add('reopen creates a new native context after pool retirement', app.contexts['reborn-a']['context_reused'] is False, app.contexts['reborn-a'])
    a=app.evaluate('reborn-a', "return await fetch('/echo').then(r=>r.json())")
    add('persistent Cookie survives context retirement and reopen', a['profile']=='A' and 'persist=A' in a['cookie'], a)
    app.close_window('reborn-a')
    app.send(op='disconnect',profile='A')
    add('zero-page connection is still retired on disconnect', app.wait('disconnected',profile='A')['environments']==1)
    app.send(op='disconnect',profile='B')
    add('final connection retirement empties environment owner', app.wait('disconnected',profile='B')['environments']==0)
    app.send(op='counts')
    counts=app.wait('counts')
    add('no retained guest or environment resources', counts['guests']==counts['environments']==counts['pooledContexts']==0, counts)
